-- QtGui: geometry, colors, fonts, images and painting, 3D math.

local T = require("testlib")
local qt = qt6

-- Geometry -------------------------------------------------------------------------------------------

T.test("QPoint and QPointF: components and operators", function()
    local p = qt.QPoint(3, -4)
    T.xy(p, 3, -4)
    T.eq(p:manhattan_length(), 7)
    T.xy(p + qt.QPoint(1, 1), 4, -3)
    T.xy(p - qt.QPoint(1, 1), 2, -5)
    T.xy(-p, -3, 4)
    T.xy(p * 2, 6, -8)
    T.ok(p == qt.QPoint(3, -4))
    T.ok(p ~= qt.QPoint(3, 4))

    local f = qt.QPointF(0.5, 1.5)
    T.xy(f * 2, 1, 3)
    T.xy(f + qt.QPointF(0.5, 0.5), 1, 2)
end)

T.test("QSize: arithmetic and aspect ratio", function()
    local size = qt.QSize(640, 480)
    T.eq(size:width(), 640)
    T.eq(size:height(), 480)
    T.ok(not size:is_empty())
    local scaled = size:scaled(320, 320, qt.Qt.KeepAspectRatio)
    T.eq(scaled:width(), 320)
    T.eq(scaled:height(), 240)
    T.ok((size + qt.QSize(1, 1)) == qt.QSize(641, 481))
    T.ok(not qt.QSize(-1, -1):is_valid())
    T.ok(qt.QSize(0, 0):is_null())
end)

T.test("QRect: queries and set operations", function()
    local r = qt.QRect(10, 20, 100, 50)
    T.rect(r, 10, 20, 100, 50)
    T.eq(r:right(), 109)
    T.eq(r:bottom(), 69)
    T.xy(r:center(), 59, 44)
    T.ok(r:contains(qt.QPoint(10, 20)))
    T.ok(not r:contains(qt.QPoint(110, 20)))

    local other = qt.QRect(60, 40, 100, 100)
    T.rect(r:intersected(other), 60, 40, 50, 30)
    T.rect(r:united(other), 10, 20, 150, 120)
    T.ok(r:intersects(other))
    T.rect(r:translated(5, 5), 15, 25, 100, 50)
    T.rect(r:adjusted(1, 2, -3, -4), 11, 22, 96, 44)
end)

T.test("QRectF and QLineF", function()
    local r = qt.QRectF(0.5, 0.5, 2, 4)
    T.near(r:width(), 2)
    T.near(r:center():y(), 2.5)

    local line = qt.QLineF(0, 0, 3, 4)
    T.near(line:length(), 5)
    T.near(line:angle(), 306.869898, 1e-5) -- counter-clockwise, with y pointing down
end)

T.test("QPolygonF and QPainterPath", function()
    local polygon = qt.QPolygonF()
    T.ok(polygon:is_empty())
    polygon:append(qt.QPointF(0, 0))
    polygon:append(qt.QPointF(4, 0))
    polygon:append(qt.QPointF(4, 3))
    T.eq(polygon:size(), 3)
    T.rect(polygon:bounding_rect(), 0, 0, 4, 3)

    local path = qt.QPainterPath()
    path:add_rect(0, 0, 10, 10)
    T.ok(path:contains(qt.QPointF(5, 5)))
    T.ok(not path:contains(qt.QPointF(15, 5)))
    T.rect(path:bounding_rect(), 0, 0, 10, 10)
end)

T.test("QRegion: union and containment", function()
    local region = qt.QRegion(qt.QRect(0, 0, 10, 10))
    region = region:united(qt.QRegion(qt.QRect(20, 0, 10, 10)))
    T.ok(region:contains(qt.QPoint(25, 5)))
    T.ok(not region:contains(qt.QPoint(15, 5)))
    T.eq(region:rect_count(), 2)
end)

-- Colors, fonts, keys ----------------------------------------------------------------------------------

T.test("QColor: names, components and conversions", function()
    local c = qt.QColor("steelblue")
    T.ok(c:is_valid())
    T.eq(c:name(), "#4682b4")
    T.eq(c:red(), 70)
    T.eq(c:green(), 130)
    T.eq(c:blue(), 180)
    T.eq(qt.QColor(255, 128, 0):name(), "#ff8000")
    T.eq(qt.QColor(255, 128, 0, 64):alpha(), 64)
    T.ok(not qt.QColor("not a color"):is_valid())
    T.eq(qt.QColor.from_hsv(120, 255, 255):name(), "#00ff00")
    T.eq(qt.QColor(qt.Qt.red):name(), "#ff0000")
end)

T.test("QColor: lighter, darker and equality", function()
    local base = qt.QColor(100, 100, 100)
    T.ok(base:lighter(200):red() > 100)
    T.ok(base:darker(200):red() < 100)
    T.ok(qt.QColor("red") == qt.QColor(255, 0, 0))
    T.ok(qt.QColor("red") ~= qt.QColor("blue"))
end)

T.test("QFont: properties", function()
    local font = qt.QFont("Helvetica", 14)
    T.eq(font:family(), "Helvetica")
    T.eq(font:point_size(), 14)
    T.ok(not font:bold())
    font:set_bold(true)
    font:set_italic(true)
    T.ok(font:bold())
    T.ok(font:italic())
    font:set_point_size(20)
    T.eq(font:point_size(), 20)
end)

T.test("QKeySequence: parsing and formatting", function()
    local sequence = qt.QKeySequence("Ctrl+Shift+S")
    T.eq(sequence:count(), 1)
    T.eq(sequence:to_string(qt.QKeySequence.PortableText), "Ctrl+Shift+S")
    T.ok(qt.QKeySequence("Ctrl+S") == qt.QKeySequence("Ctrl+S"))
end)

-- Images and painting --------------------------------------------------------------------------------

T.test("QImage: pixels", function()
    local image = qt.QImage(4, 3, qt.QImage.Format_ARGB32)
    T.eq(image:width(), 4)
    T.eq(image:height(), 3)
    T.ok(not image:is_null())
    image:fill(qt.QColor("red"))
    T.eq(image:pixel_color(1, 1):name(), "#ff0000")
    image:set_pixel_color(2, 1, qt.QColor("blue"))
    T.eq(image:pixel_color(2, 1):name(), "#0000ff")
    T.eq(image:pixel_color(0, 0):name(), "#ff0000")
    T.ok(image:valid(3, 2))
    T.ok(not image:valid(4, 3))
end)

T.test("QImage: transformations", function()
    local image = qt.QImage(10, 20, qt.QImage.Format_RGB32)
    image:fill(qt.QColor("white"))
    T.eq(image:scaled(5, 10):width(), 5)
    T.eq(image:flipped(qt.Qt.Vertical):height(), 20)
    T.eq(image:transformed(qt.QTransform():rotate(90)):width(), 20)
    T.eq(image:copy(qt.QRect(0, 0, 3, 3)):width(), 3)
    T.eq(image:convert_to_format(qt.QImage.Format_Grayscale8):format(), qt.QImage.Format_Grayscale8)
end)

T.test("QPainter: draws into an image", function()
    local image = qt.QImage(20, 20, qt.QImage.Format_ARGB32)
    image:fill(qt.QColor("white"))

    local painter = qt.QPainter(image)
    T.ok(painter:is_active())
    painter:fill_rect(5, 5, 10, 10, qt.QColor("green"))
    painter:set_pen(qt.QColor("black"))
    painter:draw_line(0, 0, 19, 0)
    painter:end_()

    T.ok(not painter:is_active())
    T.eq(image:pixel_color(10, 10):name(), "#008000")
    T.eq(image:pixel_color(1, 15):name(), "#ffffff")
    T.eq(image:pixel_color(10, 0):name(), "#000000")
end)

T.test("QPainter: transforms and clipping", function()
    local image = qt.QImage(20, 20, qt.QImage.Format_ARGB32)
    image:fill(qt.QColor("white"))
    local painter = qt.QPainter(image)
    painter:translate(10, 10)
    painter:fill_rect(0, 0, 5, 5, qt.QColor("red"))
    painter:end_()
    T.eq(image:pixel_color(12, 12):name(), "#ff0000")
    T.eq(image:pixel_color(2, 2):name(), "#ffffff")
end)

T.test("QImage: save and load through a file", function()
    local directory = qt.QTemporaryDir()
    local path = directory:path() .. "/picture.png"

    local image = qt.QImage(8, 8, qt.QImage.Format_ARGB32)
    image:fill(qt.QColor(10, 20, 30))
    T.ok(image:save(path))

    local loaded = qt.QImage(path)
    T.eq(loaded:width(), 8)
    T.eq(loaded:pixel_color(3, 3):name(), "#0a141e")
end)

T.test("QPixmap: size and conversion", function()
    local pixmap = qt.QPixmap(30, 10)
    pixmap:fill(qt.QColor("yellow"))
    T.eq(pixmap:width(), 30)
    T.eq(pixmap:height(), 10)
    T.eq(pixmap:to_image():pixel_color(0, 0):name(), "#ffff00")
end)

-- 3D math --------------------------------------------------------------------------------------------

T.test("QVector3D: arithmetic", function()
    local a, b = qt.QVector3D(1, 2, 3), qt.QVector3D(4, 5, 6)
    T.near(qt.QVector3D.dot_product(a, b), 32)
    local cross = qt.QVector3D.cross_product(qt.QVector3D(1, 0, 0), qt.QVector3D(0, 1, 0))
    T.near(cross:z(), 1)
    T.near((a + b):x(), 5)
    T.near((b - a):y(), 3)
    T.near((a * 2):z(), 6)
    T.near((-a):x(), -1)
    T.near((b / 2):x(), 2)
    T.near(qt.QVector3D(3, 4, 0):length(), 5)
    T.near(qt.QVector3D(3, 4, 0):normalized():x(), 0.6)
end)

T.test("QQuaternion: rotation", function()
    local rotation = qt.QQuaternion.from_axis_and_angle(qt.QVector3D(0, 0, 1), 90)
    local rotated = rotation:rotated_vector(qt.QVector3D(1, 0, 0))
    T.near(rotated:x(), 0, 1e-5)
    T.near(rotated:y(), 1, 1e-5)
    local twice = rotation * rotation
    T.near(twice:rotated_vector(qt.QVector3D(1, 0, 0)):x(), -1, 1e-5)
end)

T.test("QMatrix4x4: transforms a point", function()
    local matrix = qt.QMatrix4x4()
    matrix:translate(1, 2, 3)
    matrix:scale(2)
    local mapped = matrix:map(qt.QVector3D(1, 1, 1))
    T.near(mapped:x(), 3)
    T.near(mapped:y(), 4)
    T.near(mapped:z(), 5)
    T.ok((matrix * matrix:inverted()):is_identity())
end)

T.test("QTransform: maps points and composes", function()
    local transform = qt.QTransform():translate(10, 20)
    local mapped = transform:map(qt.QPointF(1, 1))
    T.xy(mapped, 11, 21)
    T.xy(transform:map(qt.QPoint(1, 1)), 11, 21)
    T.near(transform:dx(), 10)
    local scaled = transform * qt.QTransform():scale(2, 2)
    T.xy(scaled:map(qt.QPointF(1, 1)), 22, 42)
end)

T.run()
