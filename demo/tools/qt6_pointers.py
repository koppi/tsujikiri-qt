#!/usr/bin/env python3
"""Writes qt6_pointers.h: how pointers to the bound classes cross into Lua.

LuaBridge3 treats every `T*` alike, which is not good enough for Qt:

  * `nil` has to be a null pointer in the overload sets too (widget:set_parent(nil)), where
    LuaBridge3 only accepts userdata, and
  * what Qt returns as a QObject* or QEvent* is often an object of a derived class, which has
    to arrive in Lua as that class (a QWidget* that is a QPushButton has text()).

Both are done by qt6::PointerStack<T>, and a Stack<T*> and Stack<const T*> specialization naming
it has to be visible wherever T* is converted. So the list of the classes that are bound (written by
qt6_gen.py for every module) becomes this header, which support/qt6_lua.h includes.

    qt6_pointers.py --output qt6_pointers.h --include QtCore/QtCore ... qt6_core.classes ...
"""

import argparse
from pathlib import Path

HEADER = """// DO NOT EDIT - generated by tools/qt6_pointers.py
#pragma once

{includes}

namespace luabridge {{

{specializations}
}} // namespace luabridge
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--output", required=True)
    parser.add_argument("--include", action="append", default=[], help="a header that declares the classes, without <>")
    parser.add_argument("classes", nargs="+", help="files with the names of the bound classes, one per line")
    args = parser.parse_args()

    names = set()
    for path in args.classes:
        names.update(line.strip() for line in Path(path).read_text(encoding="utf-8").splitlines() if line.strip())

    includes = "\n".join(f"#include <{inc}>" for inc in args.include)
    specializations = "\n".join(
        f"template <> struct Stack<{name}*> : qt6::PointerStack<{name}> {{}};\n"
        f"template <> struct Stack<const {name}*> : qt6::PointerStack<const {name}> {{}};"
        for name in sorted(names)
    )

    content = HEADER.format(includes=includes, specializations=specializations)
    output = Path(args.output)
    if not output.exists() or output.read_text(encoding="utf-8") != content:
        output.write_text(content, encoding="utf-8")
    print(f"{len(names)} classes -> {output}")


if __name__ == "__main__":
    main()
