#!/usr/bin/env python3
"""Generates the Lua bindings of the Qt 6.8 that koppi/os vendors (QtCore, QtGui, QtWidgets).

The desktop build (demo/CMakeLists.txt) binds a full Qt; this binds the *partial* Qt of the
operating system, for its 32-bit ring-3 programs. Everything is the same pipeline (tsujikiri, the
qt6 stage of demo/tools/qt6_gen.py, demo/support/qt6_lua.*), with three differences that all follow
from "the library is not the whole of Qt":

  * the headers are parsed the way the compiler gets them (-m32, the OS's QT_NO_* macros and
    config headers), so a feature the OS turned off is not in the bindings;
  * the umbrella headers (<QtCore/QtCore> ...) are made here, the vendored include tree has none;
  * --symbols names every function the vendored libraries define, and the qt6 stage drops what would
    not link: members that are declared but not compiled in, and the classes that are not there.

    generate.py --qt-flags "<the compiler flags of qt.mk>" --symbols defined.txt --out build/generated
"""

from __future__ import annotations

import argparse
import re
import shlex
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEMO = HERE.parents[1] / "demo"

# Module, translation units, namespaces whose classes are bound, namespace level enums
MODULES = [
    ("Core", 10, '""', '"Qt::.*", "QtMsgType"'),
    ("Gui", 8, '""', ""),
    ("Widgets", 6, '""', ""),
]

# Headers of the include tree that are not API: implementation details, helpers for the compiler
NOT_PUBLIC = re.compile(r"(?:_p|_impl|_helpers?)\.h$|^q(?:20|23|26)\w+\.h$|config|exports|tracepoints|global\.h$|^qcomparehelpers\.h$")

PARSE_ARGS = ["-x", "c++", "-m32", "-fno-exceptions", "-fno-rtti"]


def write_if_changed(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return
    path.write_text(content, encoding="utf-8")


def quoted(items) -> str:
    return ", ".join('"' + item.replace("\\", "\\\\").replace('"', '\\"') + '"' for item in items)


def split_flags(flags: str, cwd: Path):
    """(-I directories, -D definitions, the -std flag) of a compiler command line."""
    includes, defines, standard = [], [], "-std=gnu++20"
    tokens = shlex.split(flags)
    it = iter(tokens)
    for token in it:
        if token == "-I":
            includes.append(next(it))
        elif token.startswith("-I"):
            includes.append(token[2:])
        elif token == "-D":
            defines.append(next(it))
        elif token.startswith("-D"):
            defines.append(token[2:])
        elif token.startswith("-std="):
            standard = token
        elif token in ("-include", "-isystem"):
            next(it)
    includes = [str((cwd / inc).resolve()) for inc in includes]
    return includes, defines, standard


def find_qt_include(includes) -> Path:
    for inc in includes:
        if (Path(inc) / "QtCore" / "qobject.h").exists():
            return Path(inc)
    raise SystemExit("generate: no include directory has QtCore/qobject.h; is --qt-flags the flags of qt.mk?")


def umbrella(module: str, qt_include: Path, outdir: Path) -> list[str]:
    """<QtCore/QtCore> and friends: every public header of the module the include tree has."""
    headers = sorted(h.name for h in (qt_include / f"Qt{module}").glob("q*.h") if not NOT_PUBLIC.search(h.name))
    lines = [f"// DO NOT EDIT - generated by koppios/tools/generate.py", "#pragma once"]
    lines += [f"#include <Qt{module}/{h}>" for h in headers]
    write_if_changed(outdir / "include" / f"Qt{module}" / f"Qt{module}", "\n".join(lines) + "\n")
    return headers


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--qt-flags", required=True, help="the compiler flags the OS builds Qt with (-I, -D, -std), or @file with them")
    parser.add_argument("--cwd", default=".", help="what relative -I directories are relative to")
    parser.add_argument("--symbols", required=True, help="the mangled names the vendored libraries define, one per line")
    parser.add_argument("--out", required=True)
    parser.add_argument("--unbindable", action="append", default=[], help="more lists of members the compiler rejects")
    args = parser.parse_args()

    out = Path(args.out).resolve()
    out.mkdir(parents=True, exist_ok=True)
    flags = Path(args.qt_flags[1:]).read_text(encoding="utf-8") if args.qt_flags.startswith("@") else args.qt_flags
    includes, defines, standard = split_flags(flags, Path(args.cwd).resolve())
    qt_include = find_qt_include(includes)

    # The umbrella headers come first: support/qt6_lua.h includes <QtCore/QtCore>
    for module, *_ in MODULES:
        umbrella(module, qt_include, out)
    includes = [str(out / "include")] + includes

    template = (DEMO / "qt6.input.yml.in").read_text(encoding="utf-8")
    unbindable = [str(DEMO / "qt6_unbindable.txt"), str(HERE.parent / "koppios_unbindable.txt")] + [str(Path(u).resolve()) for u in args.unbindable]
    classes_files = []

    for module, parts, namespaces, enums in MODULES:
        name = f"qt6_{module.lower()}"
        header = out / f"{name}_headers.h"
        write_if_changed(header, f"#pragma once\n#include <Qt{module}/Qt{module}>\n")

        values = {
            "QT6_MODULE_HEADER": str(header),
            "QT6_MODULE": module,
            "QT6_NAMESPACES": namespaces,
            "QT6_ENUMS": enums,
            "QT6_FUNCTIONS": "",
            "QT6_UNBINDABLE_FILES": quoted(unbindable),
            "QT6_INCLUDE_PATHS": quoted(includes),
            "QT6_DEFINES": quoted(defines),
            "QT6_PARSE_ARGS": quoted(PARSE_ARGS + [standard]),
            "QT6_COMPACT_ENUMS": "true",
        }
        text = template
        for key, value in values.items():
            text = text.replace(f"@{key}@", value)
        config = out / f"{name}.input.yml"
        write_if_changed(config, text)

        classes = out / f"{name}.classes"
        classes_files.append(classes)
        print(f"== Qt{module}", flush=True)
        subprocess.run(
            [
                sys.executable, str(DEMO / "tools" / "qt6_gen.py"),
                "--input", str(config), "--parts", str(parts), "--outdir", str(out),
                "--formats-dir", str(DEMO / "formats"), "--classes-file", str(classes),
                "--symbols", args.symbols,
            ],
            check=True,
        )

    # Pointers to the bound classes (see demo/tools/qt6_pointers.py)
    pointer_args = []
    for module, *_ in MODULES:
        pointer_args += ["--include", f"Qt{module}/Qt{module}"]
    subprocess.run(
        [sys.executable, str(DEMO / "tools" / "qt6_pointers.py"), "--output", str(out / "qt6_pointers.h")] + pointer_args + [str(c) for c in classes_files],
        check=True,
    )

    # The translation units, for the makefile (an included makefile that has a rule is remade, then make starts over)
    parts = [f"qt6_{m.lower()}" for m, *_ in MODULES] + [f"qt6_{m.lower()}_p{i}" for m, count, *_ in MODULES for i in range(count)]
    write_if_changed(out / "parts.mk", "# DO NOT EDIT - generated by koppios/tools/generate.py\nPARTS := " + " ".join(parts) + "\n")

    # register_qt6(): the modules in the order of their dependencies, then the hand written parts
    declarations = "".join(f"void register_qt6_{m.lower()}(lua_State* L);\n" for m, *_ in MODULES)
    calls = "".join(f"    register_qt6_{m.lower()}(L);\n" for m, *_ in MODULES)
    write_if_changed(
        out / "qt6_register.cpp",
        "// DO NOT EDIT - generated by koppios/tools/generate.py\n"
        '#include "qt6_lua.h"\n\n'
        f"{declarations}\nvoid register_qt6(lua_State* L)\n{{\n{calls}    qt6::registerSupport(L);\n}}\n",
    )


if __name__ == "__main__":
    main()
